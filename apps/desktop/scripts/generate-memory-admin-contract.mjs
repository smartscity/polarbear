import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const contract = JSON.parse(readFileSync(resolve(root, "contracts/memory/admin-v1.json"), "utf8"));
const types = readFileSync(resolve(root, "contracts/memory/admin-v1.types.ts"), "utf8").trim();
const outputPath = resolve(root, "src/features/memory/generated/adminV1.ts");
const rustProxy = readFileSync(resolve(root, "src-tauri/src/memory_admin.rs"), "utf8");
const output = `// Generated by scripts/generate-memory-admin-contract.mjs. Do not edit.\nexport const MEMORY_ADMIN_API_VERSION = ${JSON.stringify(contract.version)} as const;\n\nexport const MEMORY_CAPABILITIES = ${JSON.stringify(contract.capabilities, null, 2)} as const;\n\nexport type MemoryCapability = (typeof MEMORY_CAPABILITIES)[number];\n${types}\n`;

if (process.argv.includes("--check")) {
  if (readFileSync(outputPath, "utf8") !== output) {
    console.error("Memory Admin DTOs have drifted. Run npm run memory-contract:generate.");
    process.exitCode = 1;
  }
  const allowlistBody = rustProxy.match(/const ALLOWED_METHODS:[\s\S]*?=\s*&\[([\s\S]*?)\];/)?.[1] ?? "";
  const rustCapabilities = [...allowlistBody.matchAll(/"([^"]+)"/g)].map((match) => match[1]);
  const expected = ["system.hello", ...contract.capabilities];
  if (JSON.stringify(rustCapabilities) !== JSON.stringify(expected) || !rustProxy.includes(`const API_VERSION: &str = "${contract.version}";`)) {
    console.error("Rust Memory proxy allowlist/version has drifted from the Admin contract.");
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, output);
}
